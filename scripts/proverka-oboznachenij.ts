import { vypravitOboznacheniya } from "../src/lib/oboznacheniya";

/*
  Проверка на настоящих фразах из расшифровки лекции матанализа плюс ловушки, ради которых
  список разделён надвое.
*/

const sluchai: [string, string][] = [
  // безусловные замены
  ["функция от икс равна икс в квадрате", "функция от x равна x в квадрате"],
  ["возьмём игрек больше нуля", "возьмём y больше нуля"],
  ["для любого эпсилон больше нуля", "для любого ε больше нуля"],
  // мусор распознавателя
  ["точка igrek лежит выше", "точка y лежит выше"],
  // условные: рядом есть математика
  ["для всех эн больше пяти", "для всех n больше пяти"],
  ["функция эф от икс", "функция f от x"],
  // условные: математики рядом нет, трогать нельзя
  ["а потом мы вернёмся к теме", "а потом мы вернёмся к теме"],
  ["ка примерно так же важно, как разговор", "ка примерно так же важно, как разговор"],
  // слово внутри другого слова не трогаем
  ["пирог и пикник", "пирог и пикник"],
  ["множество иксов", "множество иксов"],
];

let oshibok = 0;

for (const [vhod, zhdem] of sluchai) {
  const { tekst } = vypravitOboznacheniya(vhod);
  const ok = tekst === zhdem;
  if (!ok) {
    oshibok++;
    console.log(`НЕ СОШЛОСЬ\n  вход:   ${vhod}\n  ждали:  ${zhdem}\n  вышло:  ${tekst}`);
  }
}

console.log(`${sluchai.length - oshibok} из ${sluchai.length}`);
process.exit(oshibok === 0 ? 0 : 1);
